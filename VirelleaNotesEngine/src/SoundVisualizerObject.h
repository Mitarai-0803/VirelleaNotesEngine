//----------------------------------------------------------------------------
//! @file   SoundVisualizerObject.h
//! @brief  サウンドビジュアライザーのインターフェース
//! @detail 音声波形解析結果を元にビジュアライザーを描画するための GameObject インターフェースを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include "Structs.h"
#include "AudioConstants.h"
#include "UIConstants.h"
#include <vector>
#include <array>

namespace UI
{
	//============================================================================
	//! @class  SoundVisualizerObject
	//! 音声のスペクトラムを描画するためのオブジェクトです。
	//============================================================================
	class SoundVisualizerObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		SoundVisualizerObject() = default;

		//-----------------------------------------------------------
		//! @brief デストラクタ
		//-----------------------------------------------------------
		~SoundVisualizerObject() = default;

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 終了処理
		//-----------------------------------------------------------
		void OnEnd() override;

		//-----------------------------------------------------------
		//! @brief 解析音源ハンドル設定
		//! @param [in] handle 音声解析に使用するソフトサウンドのハンドル
		//-----------------------------------------------------------
		void SetSoftHandle(int handle);

		//-----------------------------------------------------------
		//! @brief 再生位置設定
		//! @param [in] sample_time 再生位置（サンプル単位）
		//-----------------------------------------------------------
		void SetSampleTime(int sample_time);

		//-----------------------------------------------------------
		//! @brief ビジュアライザー描画位置設定
		//! @param [in] x 描画基準X
		//! @param [in] y 描画基準Y
		//-----------------------------------------------------------
		void SetPosition(int x, int y);

	private:
		IntPos sound_visualizer_pos_ { 0, 0 };                //!< ビジュアライザーの描画基準座標
		int    sound_handle_ { 0 };                           //!< サウンドハンドル（再生用）
		int    soft_sound_handle_ { 0 };                      //!< ソフトサウンドハンドル（解析用）
		int    sample_pos_ { 0 };                             //!< 現在の再生位置（サンプル）
		float  param_list_[BUFFERLENGTH] {};                  //!< 表示用のパラメータ配列
		bool   one_load_flag_ { false };                      //!< 一度だけ読み込んだかどうかのフラグ
		std::array<int, BUFFERLENGTH> bar_half_widths_ {};    //!< 各バーの半幅キャッシュ
		std::array<int, BUFFERLENGTH> upper_y_ {};            //!< 上側バーのY座標キャッシュ
		std::array<int, BUFFERLENGTH> lower_y_ {};            //!< 下側バーのY座標キャッシュ
	};
}
