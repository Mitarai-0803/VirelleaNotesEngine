//----------------------------------------------------------------------------
//! @file   BpmGridObject.h
//! @brief  BPMグリッド描画オブジェクトの宣言
//! @detail BPMに合わせたグリッド線を描画します。
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include "UIConstants.h"
#include "GameConstants.h"
#include "MyLibraryFunctions.h"

namespace UI
{
	//============================================================================
	//! @class  BpmGridObject
	//! BPMに合わせたグリッド線を描画するためのクラスです。
	//============================================================================
	class BpmGridObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 最大再生時間設定
		//! @param [in] max_play_time_ms 最大再生時間(ms)
		//-----------------------------------------------------------
		void SetMaxPlayTime(int max_play_time_ms);

		//-----------------------------------------------------------
		//! @brief ズーム値設定
		//! @param [in] zoom ズーム値
		//-----------------------------------------------------------
		void SetZoom(float zoom);

		//-----------------------------------------------------------
		//! @brief スクロールY値設定
		//! @param [in] scroll_y スクロールY値
		//-----------------------------------------------------------
		void SetScrollY(float scroll_y);

		//-----------------------------------------------------------
		//! @brief BPM設定
		//! @param [in] bpm BPM値
		//-----------------------------------------------------------
		void SetBpm(int bpm);

		//-----------------------------------------------------------
		//! @brief 最大スクロールY値取得
		//! @return 最大スクロールY値
		//-----------------------------------------------------------
		float GetMaxScrollY() const;

	private:
		//-----------------------------------------------------------
		//! @brief BPMグリッド描画
		//-----------------------------------------------------------
		void DrawBpmGrid();

		int max_play_time_ms_ = 0;     //!< 最大再生時間(ms)
		float zoom_ = 0.0f;            //!< ズーム値
		float scroll_y_ = 0.0f;        //!< スクロールY値
		int bpm_ = 0;                  //!< BPM値
		float max_scroll_y_ = 0.0f;    //!< 最大スクロールY値

		// キャッシュ変数
		float interval_sec_ = 0.0f;    //!< 拍間隔(秒)
		int line_count_ = 0;           //!< ライン総数
		float y_offset_ = 0.0f;        //!< Y座標オフセット
		int start_i_ = 0;              //!< 描画開始インデックス
		int end_i_ = 0;                //!< 描画終了インデックス

		// 描画時随時更新変数
		int draw_start_ = 0;           //!< 描画開始インデックス
		int draw_end_ = 0;             //!< 描画終了インデックス
		float draw_y_ = 0.0f;          //!< 描画Y座標
		int draw_start_x_ = 0;         //!< 描画開始X座標
		int draw_end_x_ = 0;           //!< 描画終了X座標
		unsigned int draw_color_ = 0;  //!< 描画色
		int draw_line_width_ = 0;      //!< ライン幅
		int draw_label_y_ = 0;         //!< ラベルY座標
	};
}
