//----------------------------------------------------------------------------
//! @file   AudioManagerComponent.h
//! @brief  音源管理コンポーネントのヘッダ
//! @detail 音源の再生・停止、音量変更、現在位置取得などのインターフェースを定義します。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"

namespace Audio
{
	//============================================================================
	//! @class  AudioManagerComponent
	//! 音源の再生・停止と位置管理を行うコンポーネントです。
	//============================================================================
	class AudioManagerComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		AudioManagerComponent();

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void Init();

		//-----------------------------------------------------------
		//! @brief 毎フレームの更新処理
		//-----------------------------------------------------------
		void Update();

		//-----------------------------------------------------------
		//! @brief 終了処理
		//-----------------------------------------------------------
		void End();

		//-----------------------------------------------------------
		//! @brief 音源再生
		//-----------------------------------------------------------
		void HandlePlaySound();

		//-----------------------------------------------------------
		//! @brief 音源停止
		//-----------------------------------------------------------
		void HandleStopSound();

		//-----------------------------------------------------------
		//! @brief 音源ハンドル設定
		//! @param [in] handle 設定する音源ハンドル
		//-----------------------------------------------------------
		void SetHandle(int handle);

		//-----------------------------------------------------------
		//! @brief 音量設定
		//! @param [in] volume 設定する音量
		//-----------------------------------------------------------
		void SetVolume(int volume);

		//-----------------------------------------------------------
		//! @brief 再生位置シーク
		//! @param [in] msTime シークする時間（ミリ秒）
		//-----------------------------------------------------------
		void Seek(int msTime);

		//-----------------------------------------------------------
		//! @brief 停止位置取得
		//! @return 停止位置（ミリ秒）
		//-----------------------------------------------------------
		int GetStopPosition() const;

		//-----------------------------------------------------------
		//! @brief 再生位置取得（サンプル単位）
		//! @return 再生位置（サンプル単位）
		//-----------------------------------------------------------
		int GetSampleTime() const;

		//-----------------------------------------------------------
		//! @brief 再生位置取得（ミリ秒単位）
		//! @return 再生位置（ミリ秒単位）
		//-----------------------------------------------------------
		int GetMsTime() const;

		//-----------------------------------------------------------
		//! @brief 再生状態取得
		//! @return 再生中ならtrue
		//-----------------------------------------------------------
		bool GetPlayeMode() const;

	private:
		int load_handle_ = 0;        //!< 音源ハンドル（DxLib）
		int stop_position_ = 0;      //!< 停止位置（ミリ秒）
		int prev_volume_ = 0;        //!< 前フレームの音量
		int current_volume_ = 0;     //!< 現在の音量
		int sample_time_pos_ = 0;    //!< サンプル時間位置
		int ms_time_pos_ = 0;        //!< ミリ秒時間位置
		bool play_mode_ = false;     //!< 再生中かどうか(true = 再生中)
	};
}
