//----------------------------------------------------------------------------
//! @file   MusicPlayButton.h
//! @brief  音楽再生ボタンの宣言
//! @detail 音楽の再生・停止を制御するボタンを定義します。
////----------------------------------------------------------------------------
#pragma once
#include "ImageButton.h"

namespace UI
{
	//============================================================================
	//! @class  MusicPlayButton
	//! 音楽の再生・停止を制御するためのクラスです。
	//============================================================================
	class MusicPlayButton : public ImageButton
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 終了処理
		//-----------------------------------------------------------
		void OnEnd() override;

		//-----------------------------------------------------------
		//! @brief 音源ハンドル設定
		//! @param [in] music_handle 音源ハンドル
		//-----------------------------------------------------------
		void SetHandle(int music_handle);

		//-----------------------------------------------------------
		//! @brief 音源の音量設定
		//! @param [in] volume 設定する音量
		//-----------------------------------------------------------
		void SetVolume(int volume);

		//-----------------------------------------------------------
		//! @brief シーク位置設定
		//! @param [in] seekPosition 設定するシーク位置
		//-----------------------------------------------------------
		void SetSeekPosition(int seekPosition);

	private:
		int handle_ = 0;           //!< 音源ハンドル
		int volume_ = 0;           //!< 音量
		bool was_on_ = false;      //!< 押下状態フラグ
		int seek_position_ = 0;    //!< シーク位置
	};
} // namespace UI