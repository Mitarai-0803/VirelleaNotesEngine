//----------------------------------------------------------------------------
//! @file   SceneBase.h
//! @brief  シーン基底クラスの宣言
//! @detail シーン内のオブジェクト管理およびライフサイクルを提供します。
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include <vector>
#include <memory>
#include <string>

namespace Scene
{
	//============================================================================
	//! @class  SceneBase
	//! シーン内のオブジェクト管理およびライフサイクルを提供するためのクラスです。
	//============================================================================
	class SceneBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief シーン初期化
		//-----------------------------------------------------------
		virtual void Init();

		//-----------------------------------------------------------
		//! @brief シーン更新
		//-----------------------------------------------------------
		virtual void Update();

		//-----------------------------------------------------------
		//! @brief シーン描画
		//-----------------------------------------------------------
		virtual void Draw();

		//-----------------------------------------------------------
		//! @brief シーン終了処理
		//-----------------------------------------------------------
		virtual void End();

	protected:
		//-----------------------------------------------------------
		//! @brief シーン固有の初期化処理
		//-----------------------------------------------------------
		virtual void SceneInit() {}

		//-----------------------------------------------------------
		//! @brief シーン固有の更新処理
		//-----------------------------------------------------------
		virtual void SceneUpdate() {}

		//-----------------------------------------------------------
		//! @brief シーン固有の描画処理
		//-----------------------------------------------------------
		virtual void SceneDraw() {}

		//-----------------------------------------------------------
		//! @brief シーン固有の終了処理
		//-----------------------------------------------------------
		virtual void SceneEnd() {}

		//-----------------------------------------------------------
		//! @brief オブジェクト追加
		//! @param [in] obj 追加するオブジェクト(shared_ptr)
		//-----------------------------------------------------------
		void AddObject(std::shared_ptr<GameObject> obj);

		//-----------------------------------------------------------
		//! @brief オブジェクト追加（名前付き）
		//! @tparam T オブジェクトの型
		//! @param [in] obj_name 追加するオブジェクトの名前
		//-----------------------------------------------------------
		template <typename T>
		void AddObjectSetName(const std::string& obj_name)
		{
			auto obj = std::make_shared<T>();
			obj->SetName(obj_name);
			obj->OnInit();
			scene_objects_.push_back(obj);
		}

		//-----------------------------------------------------------
		//! @brief シーン内オブジェクト取得
		//! @tparam T 取得したい型（GameObject または派生型）
		//! @param [in] name オブジェクト名
		//! @return 見つかれば shared_ptr<T>、なければ nullptr
		//-----------------------------------------------------------
		template <typename T>
		std::shared_ptr<T> GetSceneObject(const std::string& name) const
		{
			for (auto& obj : scene_objects_)
			{
				if (obj->GetName() == name)
				{
					return std::dynamic_pointer_cast<T>(obj);
				}
			}

			return nullptr;
		}

		//-----------------------------------------------------------
		//! @brief シーン内オブジェクトの初期化呼び出し
		//-----------------------------------------------------------
		void ObjectInit();

		//-----------------------------------------------------------
		//! @brief シーン内オブジェクトの更新呼び出し
		//-----------------------------------------------------------
		void ObjectUpdate();

		//-----------------------------------------------------------
		//! @brief シーン内オブジェクトの描画呼び出し
		//-----------------------------------------------------------
		void ObjectDraw();

		//-----------------------------------------------------------
		//! @brief シーン内オブジェクトの終了呼び出し
		//-----------------------------------------------------------
		void ObjectEnd();

		std::vector<std::shared_ptr<GameObject>> scene_objects_;    //!< シーンが保持するオブジェクト
		int frame_count_ = 0;                                       //!< シーンのフレームカウント(FPSではない)
	};
}
