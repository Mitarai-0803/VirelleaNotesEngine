#include "GridComponent.h"

namespace UI
{
	//-----------------------------------------------------------
	/// @brief コンストラクタ
	//-----------------------------------------------------------
	GridComponent::GridComponent()
		: line_count_(4), max_play_time_ms_(0), bpm_(0), zoom_(0.0f), scroll_y_(0), max_scroll_y_(0)
	{
	}

	//-----------------------------------------------------------
	/// @brief 描画処理（このコンポーネントは状態保持のみ）
	//-----------------------------------------------------------
	void GridComponent::Draw()
	{
	}

	//-----------------------------------------------------------
	/// @brief 線数設定
	//-----------------------------------------------------------
	void GridComponent::SetLineCount(int line_count)
	{
		line_count_ = line_count; //!< メンバ変数に設定
	}

	//-----------------------------------------------------------
	/// @brief 最大再生時間設定
	//-----------------------------------------------------------
	void GridComponent::SetMaxPlayTime(int max_play_time_ms)
	{
		max_play_time_ms_ = max_play_time_ms; //!< メンバ変数に設定
	}

	//-----------------------------------------------------------
	/// @brief BPM設定
	//-----------------------------------------------------------
	void GridComponent::SetBpm(int bpm)
	{
		bpm_ = bpm; //!< メンバ変数に設定
	}

	//-----------------------------------------------------------
	/// @brief ズーム設定
	//-----------------------------------------------------------
	void GridComponent::SetZoom(float zoom)
	{
		zoom_ = zoom; //!< メンバ変数に設定
	}

	//-----------------------------------------------------------
	/// @brief スクロール量設定
	//-----------------------------------------------------------
	void GridComponent::SetScrollY(int scroll_y)
	{
		scroll_y_ = scroll_y; //!< メンバ変数に設定
	}

	//-----------------------------------------------------------
	/// @brief 最大スクロールY座標を取得
	//-----------------------------------------------------------
	int GridComponent::GetMaxScrollY()
	{
		return max_scroll_y_; //!< 最大スクロールY返却
	}

	//-----------------------------------------------------------
	/// @brief BPMを取得
	//-----------------------------------------------------------
	int GridComponent::GetBpm()
	{
		return bpm_; //!< BPM返却
	}
}
