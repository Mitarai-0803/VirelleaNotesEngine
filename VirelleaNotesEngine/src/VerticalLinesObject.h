//----------------------------------------------------------------------------
//! @file   VerticalLinesObject.h
//! @brief  縦線オブジェクトの宣言
//! @detail 画面に縦線を描画するためのオブジェクトを定義します。
//----------------------------------------------------------------------------
#pragma once

#include "GameObject.h"
#include "UIConstants.h"
#include <vector>

namespace UI
{
	//============================================================================
	//! @class  VerticalLinesObject
	//! 画面に縦線を描画するためのクラスです。
	//============================================================================
	class VerticalLinesObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 縦線本数設定
		//! @param [in] line_count 縦線の本数
		//-----------------------------------------------------------
		void SetLineCount(int line_count);

	private:
		int line_count_ = 0;                   //!< 縦線の本数
		float total_width_cached_ = 0.0f;      //!< 総ライン幅キャッシュ
		float start_x_cached_ = 0.0f;          //!< 開始X位置キャッシュ
		std::vector<float> line_positions_;    //!< 各縦線のX座標キャッシュ
	};
}
