//----------------------------------------------------------------------------
//! @file   ImageObject.h
//! @brief  画像オブジェクトの宣言
//! @detail 画像を読み込み座標を設定して描画するGameObjectクラスを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include "Structs.h"
#include <string>

namespace UI
{
	//============================================================================
	//! @class  ImageObject
	//! 画像を読み込み描画するためのクラスです。
	//============================================================================
	class ImageObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief 読み込む画像パス設定
		//! @param [in] path 画像パス
		//-----------------------------------------------------------
		void SetPath(const char* path);

		//-----------------------------------------------------------
		//! @brief 座標設定
		//! @param [in] pos 座標
		//-----------------------------------------------------------
		void SetPos(FloatPos pos);

	protected:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 終了処理
		//-----------------------------------------------------------
		void OnEnd() override;

		FloatPos pos_{ 0.0f, 0.0f };    //!< 座標
		int image_handle_ = 0;          //!< 画像ハンドル
		std::string image_path_;        //!< 読み込んだ画像パス（キャッシュ管理用）

		// 描画用キャッシュ
		bool has_image_ = false;        //!< 画像が有効かどうかのキャッシュ
		int draw_x_int_ = 0;            //!< 描画X座標(整数)
		int draw_y_int_ = 0;            //!< 描画Y座標(整数)
	};
}
