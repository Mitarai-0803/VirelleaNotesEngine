//----------------------------------------------------------------------------
//! @file   NoteComponent.cpp
//! @brief  ノーツコンポーネントの実装
//! @detail ノーツ生成・管理の機能を提供します。
//----------------------------------------------------------------------------
#include "NoteComponent.h"

//-----------------------------------------------------------
//! @brief 初期化処理
//-----------------------------------------------------------
void NoteComponent::Init()
{
	// 仮：3つのノーツ生成
	notes.push_back({ 300, 0, false });
	notes.push_back({ 400, -100, false });
	notes.push_back({ 500, -200, false });
}

//-----------------------------------------------------------
//! @brief 更新処理
//-----------------------------------------------------------
void NoteComponent::Update()
{
	for (auto& note : notes)
	{
		note.y += 1;

		if (note.y > 600)
			note.hit = true;
	}
}

//-----------------------------------------------------------
//! @brief 描画処理
//-----------------------------------------------------------
void NoteComponent::Draw()
{
	for (auto& note : notes)
	{
		if (!note.hit)
		{
			DrawFillBox(note.x - 16, note.y - 16, note.x + 16, note.y + 16, GetColor(255, 0, 0));
		}
	}
}

//-----------------------------------------------------------
//! @brief 終了処理
//-----------------------------------------------------------
void NoteComponent::End()
{
	notes.clear();
}
