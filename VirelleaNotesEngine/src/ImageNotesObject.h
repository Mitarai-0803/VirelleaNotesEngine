//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include "ImageObject.h"
#include "NoteObject.h"

namespace UI
{
	//============================================================================
	//! @class  ImageNotesObject
	//! ノーツタイプに応じた画像を表示するためのクラスです。
	//============================================================================
	class ImageNotesObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief デストラクタ
		//-----------------------------------------------------------
		~ImageNotesObject();

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 現在のノーツタイプ設定
		//! @param [in] note_type ノーツタイプ
		//-----------------------------------------------------------
		void SetCurrentNoteType(int note_type);

	protected:
		ImageObject notes_images_[NOTE_TYPE_MAX] = {};    //!< 画像オブジェクト
		int current_note_type_ = 0;                       //!< 現在のノーツタイプ

		// 描画位置キャッシュ
		int mouse_x_cache_ = 0;                           //!< マウスX座標キャッシュ
		int mouse_y_cache_ = 0;                           //!< マウスY座標キャッシュ
	};
} // namespace UI
