//----------------------------------------------------------------------------
//! @file   GameObject.h
//! @brief  ゲームオブジェクトの宣言
//! @detail コンポーネントを管理し、ライフサイクルを管理するクラスを定義します。
//----------------------------------------------------------------------------

#pragma once
#include "ComponentBase.h"
#include <vector>
#include <memory>
#include <type_traits>
#include <string>

//============================================================================
//! @class  GameObject
//! コンポーネントを管理し、ライフサイクルを管理するクラスです。
//============================================================================
class GameObject {
public:
    //-----------------------------------------------------------
    //! @brief コンストラクタ
    //-----------------------------------------------------------
    GameObject() = default;

    //-----------------------------------------------------------
    //! @brief デストラクタ
    //-----------------------------------------------------------
    ~GameObject();

    //-----------------------------------------------------------
    //! @brief オブジェクト名を取得
    //! @return オブジェクト名
    //-----------------------------------------------------------
    std::string GetName() const { return name_; }

    //-----------------------------------------------------------
    //! @brief オブジェクト名を設定
    //! @param [in] n 設定する名前
    //-----------------------------------------------------------
    void SetName(const std::string& n) { name_ = n; }

    //-----------------------------------------------------------
    //! @brief コンポーネント追加
    //! @tparam T 追加するコンポーネント型
    //! @param [in] args コンポーネントのコンストラクタ引数
    //! @return 追加されたコンポーネントの生ポインタ
    //-----------------------------------------------------------
    template <typename T, typename... Args>
    T* AddComponent(Args&&... args) {
        // コンポーネントを unique_ptr で作成して所有する
        auto comp = std::make_unique<T>(std::forward<Args>(args)...);
        T* ptr = comp.get();
        ptr->Init();
        components_.push_back(std::move(comp));
        return ptr;
    }

    //-----------------------------------------------------------
    //! @brief コンポーネント取得
    //! @tparam T 取得するコンポーネント型
    //! @return 該当コンポーネントの生ポインタ、なければnullptr
    //-----------------------------------------------------------
    template<typename T>
    T* GetComponent() const {
        for (const auto& comp : components_) {
            T* ptr = dynamic_cast<T*>(comp.get());
            if (ptr) return ptr;
        }
        return nullptr;
    }

    //-----------------------------------------------------------
    //! @brief コンポーネントの初期化を呼び出し
    //-----------------------------------------------------------
    void Init();

    //-----------------------------------------------------------
    //! @brief コンポーネントの更新を呼び出し
    //-----------------------------------------------------------
    void Update();

    //-----------------------------------------------------------
    //! @brief コンポーネントの描画を呼び出し
    //-----------------------------------------------------------
    void Draw();

    //-----------------------------------------------------------
    //! @brief コンポーネントの終了処理を呼び出し
    //-----------------------------------------------------------
    void End();

    //-----------------------------------------------------------
    //! @brief スクロール・ズーム描画用関数(オーバーロード用)
    //! @param [in] scroll スクロール量
    //! @param [in] zoom ズーム量
    //-----------------------------------------------------------
    virtual void Draw(float scroll, float zoom) { OnDraw(scroll, zoom); }
    virtual void OnDraw(float scroll, float zoom) {}

    //-----------------------------------------------------------
    //! @brief 描画順の設定
    //! @param [in] order 描画順（大きいほど後に描画）
    //-----------------------------------------------------------
    void SetDrawOrder(int order) { draw_order_ = order; }

    //-----------------------------------------------------------
    //! @brief 描画順の取得
    //! @return 描画順
    //-----------------------------------------------------------
    int GetDrawOrder() const { return draw_order_; }

protected:
    virtual void OnInit() {}
    virtual void OnUpdate() {}
    virtual void OnDraw() {}
    virtual void OnEnd() {}

private:
    std::vector<std::unique_ptr<ComponentBase>> components_; //!< 管理するコンポーネント
    std::string name_; //!< オブジェクト名
    int draw_order_ = 0; //!< 描画順
};
