//----------------------------------------------------------------------------
//! @file   ScrollControlComponent.h
//! @brief  スクロール制御コンポーネントの宣言
//! @detail コンテンツ全体とビュー領域の高さに基づいて、スクロール位置とスクロールバーを動的に管理します。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"

namespace System
{
	//============================================================================
	//! @class  ScrollControlComponent
	//! スクロール制御を行うためのクラスです。
	//============================================================================
	class ScrollControlComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		ScrollControlComponent();

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void Update() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void Draw() override;

		//-----------------------------------------------------------
		//! @brief コンテンツ全体の高さ設定
		//! @param [in] height コンテンツの高さ（ピクセル）
		//-----------------------------------------------------------
		void SetContentHeight(float height);

		//-----------------------------------------------------------
		//! @brief 表示領域の高さ設定
		//! @param [in] height 表示領域の高さ（ピクセル）
		//-----------------------------------------------------------
		void SetViewHeight(float height);

		//-----------------------------------------------------------
		//! @brief ズーム設定
		//! @param [in] zoom ズーム倍率（1.0 が実寸）
		//-----------------------------------------------------------
		void SetZoom(float zoom);

		//-----------------------------------------------------------
		//! @brief スクロール速度設定
		//! @param [in] speed 1回の操作あたりのスクロール量
		//-----------------------------------------------------------
		void SetScrollSpeed(float speed);

		//-----------------------------------------------------------
		//! @brief バーの位置と幅設定
		//! @param [in] x バーのX座標
		//! @param [in] width バーの幅
		//-----------------------------------------------------------
		void SetBarPosition(int x, int width);

		//-----------------------------------------------------------
		//! @brief スクロール位置取得
		//! @return 現在のスクロール値（コンテンツ座標）
		//-----------------------------------------------------------
		float GetScroll() const;

	private:
		//-----------------------------------------------------------
		//! @brief スクロール範囲とバーサイズを更新
		//-----------------------------------------------------------
		void UpdateScrollRange();

		float scroll_ = 0.0f;             //!< 現在のスクロール位置（コンテンツ座標）
		float max_scroll_ = 0.0f;         //!< コンテンツ全体の高さ（ピクセル）
		float view_height_ = 0.0f;        //!< 表示領域高さ（ピクセル）
		float max_scroll_range_ = 0.0f;   //!< スクロール可能範囲（ピクセル）
		float scroll_speed_ = 0.0f;       //!< スクロール速度
		float zoom_ = 1.0f;               //!< ズーム倍率
		int wheel_ = 0;                   //!< ホイールの回転量
		int bar_x_ = 0;                   //!< バーのX座標
		int bar_y_ = 0;                   //!< バーのY座標（描画用）
		int bar_width_ = 0;               //!< バーの幅
		int bar_height_ = 0;              //!< バーの高さ（自動計算）
		bool dragging_ = false;           //!< ドラッグ中
		int dragOffset_ = 0;              //!< バー内のクリック位置オフセット
	};
}
