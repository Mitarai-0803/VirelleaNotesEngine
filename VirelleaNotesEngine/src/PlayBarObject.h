//----------------------------------------------------------------------------
//! @file   PlayBarObject.h
//! @brief  再生バーオブジェクトの宣言
//! @detail 縦の再生バーを描画し、再生位置の変更をサポートします。
//----------------------------------------------------------------------------
#pragma once

#include "GameObject.h"
#include "UIConstants.h"
#include "GameConstants.h"
#include "Font.h"
#include "MyLibraryFunctions.h"

namespace UI
{
	//-----------------------------------------------------------
	//! @class PlayBarObject
	//! 再生位置の表示と変更を行うためのクラスです。
	//-----------------------------------------------------------
	class PlayBarObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 最大再生時間設定
		//! @param [in] max_play_time_ms 最大再生時間(ms)
		//-----------------------------------------------------------
		void SetMaxPlayTime(int max_play_time_ms);

		//-----------------------------------------------------------
		//! @brief 現在の再生時間設定
		//! @param [in] current_play_time_ms 現在の再生時間(ms)
		//-----------------------------------------------------------
		void SetCurrentPlayTime(int current_play_time_ms);

		//-----------------------------------------------------------
		//! @brief 現在の再生時間取得
		//! @return 現在の再生時間(ms)
		//-----------------------------------------------------------
		int GetCurrentPlayTime() const;

		//-----------------------------------------------------------
		//! @brief 再生位置変更イベント取得
		//! @return 再生位置が変更された場合 true
		//-----------------------------------------------------------
		bool IsSeekRequested() const;

		//-----------------------------------------------------------
		//! @brief 要求された再生位置取得
		//! @return 要求された再生位置(ms)
		//-----------------------------------------------------------
		int GetRequestedSeekTime() const;

		//-----------------------------------------------------------
		//! @brief イベントリセット
		//-----------------------------------------------------------
		void ResetSeekRequest();

	private:
		int max_play_time_ms_ = 0;     //!< 最大再生時間(ms)
		int current_play_time_ms_ = 0; //!< 現在の再生時間(ms)
		bool is_dragging_ = false;     //!< ドラッグ中フラグ
		bool seek_requested_ = false;  //!< シーク要求フラグ
		int draw_progress_y_ = 0;	   //!< 描画時の進捗Y座標キャッシュ
		int requested_seek_time_ = 0;  //!< 要求されたシーク時間(ms)
		float progress_ = 0;		   //!< 進捗割合(0.0 - 1.0)

		//-----------------------------------------------------------
		//! @brief 再生バー描画
		//-----------------------------------------------------------
		void DrawPlayBar();

		//-----------------------------------------------------------
		//! @brief マウス位置から再生時間を計算
		//! @param [in] mouse_y マウスY座標
		//! @return 計算された再生時間(ms)
		//-----------------------------------------------------------
		int CalculatePlayTimeFromMouseY(int mouse_y);
	};
} // namespace UI