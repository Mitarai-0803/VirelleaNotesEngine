//----------------------------------------------------------------------------
//! @file   PlayTimeIndicatorObject.h
//! @brief  再生時間表示オブジェクトの宣言
//! @detail 画面上に現在の再生位置を示す線と文字列を描画します。
//----------------------------------------------------------------------------
#pragma once

#include "GameObject.h"
#include "Structs.h"
#include "GameConstants.h"
#include "UIConstants.h"

namespace UI
{
	//============================================================================
	//! @class  PlayTimeIndicatorObject
	//! 再生時間の表示と現在再生位置を示すためのクラスです。
	//============================================================================
	class PlayTimeIndicatorObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		PlayTimeIndicatorObject() = default;

		//-----------------------------------------------------------
		//! @brief デストラクタ
		//-----------------------------------------------------------
		~PlayTimeIndicatorObject() = default;

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 再生位置設定
		//! @param [in] sample_time 再生位置（ミリ秒）
		//-----------------------------------------------------------
		void SetPlayTime(int sample_time);

		//-----------------------------------------------------------
		//! @brief 最大再生時間設定
		//! @param [in] max_play_time 最大再生時間（ミリ秒）
		//-----------------------------------------------------------
		void SetMaxPlayTime(int max_play_time);

		//-----------------------------------------------------------
		//! @brief 描画位置設定
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//-----------------------------------------------------------
		void SetPosition(int x, int y);

		//-----------------------------------------------------------
		//! @brief ラインの描画範囲高さ設定
		//! @param [in] height 高さ（ピクセル）
		//-----------------------------------------------------------
		void SetHeight(int height);

		//-----------------------------------------------------------
		//! @brief 文字描画に使うフォントハンドル設定
		//! @param [in] handle フォントハンドル
		//-----------------------------------------------------------
		void SetFontHandle(int handle);

		//-----------------------------------------------------------
		//! @brief 再生状態設定
		//! @param [in] is_playing 再生中ならtrue
		//-----------------------------------------------------------
		void SetIsPlaying(bool is_playing);

		//-----------------------------------------------------------
		//! @brief ズーム値設定
		//! @param [in] zoom ズーム値
		//-----------------------------------------------------------
		void SetZoom(float zoom);

		//-----------------------------------------------------------
		//! @brief スクロールY値設定
		//! @param [in] scroll_y スクロールY値
		//-----------------------------------------------------------
		void SetScrollY(float scroll_y);

	private:
		int play_time_ = 0;                            //!< 現在の再生位置(ms)
		int max_play_time_ = 0;                        //!< 楽曲の最大再生時間(ms)
		int height_ = 0;                               //!< ラインの描画範囲の高さ
		int font_handle_ = 0;                          //!< フォントハンドル
		float scroll_y_ = 0.0f;                        //!< スクロールY値
		float zoom_ = ZOOM_DEFAULT;                    //!< ズーム値
		unsigned int color_ = 0;                       //!< 表示色
		IntPos pos_ = { 0, 0 };                        //!< 描画位置
		bool is_playing_ = false;                      //!< 再生中フラグ
		int draw_line_y_ = 0;                          //!< 描画時のラインY座標キャッシュ
		int playing_label_width_ = 0;                  //!< 再生中ラベル幅キャッシュ
		int stopped_label_width_ = 0;                  //!< 停止中ラベル幅キャッシュ
		int playing_label_x_ = 0;                      //!< 再生中ラベルX座標キャッシュ
		int stopped_label_x_ = 0;                      //!< 停止中ラベルX座標キャッシュ
		const char* playing_label_text_ = "再生中";    //!< 再生中ラベルテキスト
		const char* stopped_label_text_ = "停止中";    //!< 停止中ラベルテキスト
	};
}
