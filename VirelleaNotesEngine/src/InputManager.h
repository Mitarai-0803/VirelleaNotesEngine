//----------------------------------------------------------------------------
//! @file   InputManager.h
//! @brief  入力管理の宣言
//! @detail 全キー入力を静的配列で管理するクラスを定義します。
//----------------------------------------------------------------------------
#pragma once
#include <DxLib.h>

namespace InputManager
{
	//============================================================================
	//! @class  InputManager
	//! 全キー・マウス入力の状態取得およびフレーム管理を行うためのクラスです。
	//============================================================================
	class InputManager
	{
	public:
		//-----------------------------------------------------------
		//! @brief 入力状態更新（毎フレーム呼ぶ）
		//-----------------------------------------------------------
		static void Update();

		//-----------------------------------------------------------
		//! @brief キーが押された瞬間判定
		//! @param [in] key 判定するキーコード
		//! @return 押された瞬間ならtrue
		//-----------------------------------------------------------
		static bool PushHitKey(int key);

		//-----------------------------------------------------------
		//! @brief マウスボタン押下中判定
		//! @param [in] button MOUSE_INPUT_LEFT, MOUSE_INPUT_RIGHT など
		//! @return 押下中ならtrue
		//-----------------------------------------------------------
		static bool CheckMouseInput(int button);

		//-----------------------------------------------------------
		//! @brief マウスボタン押下瞬間判定
		//! @param [in] button MOUSE_INPUT_LEFT, MOUSE_INPUT_RIGHT など
		//! @return 押された瞬間ならtrue
		//-----------------------------------------------------------
		static bool PushMouseInput(int button);

		//-----------------------------------------------------------
		//! @brief マウスホイール回転量取得
		//! @return 1以上 = 奥回転, 0 = 回していない, -1以下 = 手前回転
		//-----------------------------------------------------------
		static int GetMouseWheel();

		//-----------------------------------------------------------
		//! @brief マウスX座標取得
		//! @return マウスX座標
		//-----------------------------------------------------------
		static int GetMouseX();

		//-----------------------------------------------------------
		//! @brief マウスY座標取得
		//! @return マウスY座標
		//-----------------------------------------------------------
		static int GetMouseY();

		static char key_buffer_[256];     //!< キー押下状態バッファ
		static int key_frame_[256];       //!< キー押下フレームカウンタ
		static int mouse_left_frame_;     //!< 左マウスボタン押下フレーム
		static int mouse_right_frame_;    //!< 右マウスボタン押下フレーム
		static int mouse_wheel_rot_;      //!< マウスホイール回転量
	};
}
