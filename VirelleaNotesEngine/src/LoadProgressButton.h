//----------------------------------------------------------------------------
//! @file   LoadProgressButton.h
//! @brief  途中データ読み込みボタンの宣言
//! @detail CSVファイルと音源を読み込み、途中から譜面を再開するためのボタンクラスを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "ImageButton.h"
#include "NoteObject.h"
#include <string>
#include <vector>
#include <memory>

namespace UI
{
	//============================================================================
	//! @class  LoadProgressButton
	//! CSVファイルと音源を読み込み、途中から譜面を開始するためのクラスです。
	//============================================================================
	class LoadProgressButton : public ImageButton
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief 終了処理
		//-----------------------------------------------------------
		void OnEnd() override;

		//-----------------------------------------------------------
		//! @brief 読み込んだノーツデータ取得
		//! @return 読み込まれたノーツデータ
		//-----------------------------------------------------------
		const std::vector<std::shared_ptr<NoteObject>>& GetLoadedNotes() const { return loaded_notes_; }

		//-----------------------------------------------------------
		//! @brief 読み込んだ音源ファイルパス取得
		//! @return 音源ファイルパス
		//-----------------------------------------------------------
		const std::string& GetMusicFilePath() const { return music_file_path_; }

		//-----------------------------------------------------------
		//! @brief 読み込み成功フラグ取得
		//! @return 読み込みに成功したらtrue
		//-----------------------------------------------------------
		bool IsLoadSuccess() const { return load_success_; }

		//-----------------------------------------------------------
		//! @brief 読み込んだデータを取得して内部状態をクリア
		//! @param [out] outNotes 読み込んだノーツ配列を移動で返却
		//! @param [out] outMusicPath 読み込んだ音源パスを返却
		//! @return 読み込み成功フラグが立っていればtrue（取得して内部状態をクリア）
		//-----------------------------------------------------------
		bool ConsumeLoadSuccess(std::vector<std::shared_ptr<NoteObject>>& outNotes, std::string& outMusicPath);

	private:
		//-----------------------------------------------------------
		//! @brief CSVファイルからノーツデータ読み込み
		//! @param [in] filepath CSVファイルパス
		//! @return 読み込みに成功したらtrue
		//-----------------------------------------------------------
		bool LoadNotesFromCSV(const char* filepath);

		//-----------------------------------------------------------
		//! @brief ファイル選択ダイアログ表示
		//! @param [out] filepath 選択されたファイルパス
		//! @param [in] filter ファイルフィルタ
		//! @return ファイルが選択されたらtrue
		//-----------------------------------------------------------
		bool ShowFileDialog(std::string& filepath, const char* filter);

		std::vector<std::shared_ptr<NoteObject>> loaded_notes_ {};    //!< 読み込んだノーツデータ
		std::string music_file_path_ {};                              //!< 読み込んだ音源ファイルパス
		bool load_success_ = false;                                   //!< 読み込み成功フラグ
		int load_message_timer_ = 0;                                  //!< 読み込みメッセージ表示タイマー
	};
}
