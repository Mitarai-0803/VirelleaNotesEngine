//----------------------------------------------------------------------------
//! @file   ZoomComponent.h
//! @brief  ズーム制御コンポーネントの宣言
//! @detail Ctrl + マウスホイールでズーム倍率を変更するためのコンポーネントを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "ComponentBase.h"
#include "GameConstants.h"

namespace System
{
	//============================================================================
	//! @class  ZoomComponent
	//! ズーム制御を行うコンポーネントです。
	//============================================================================
	class ZoomComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		ZoomComponent();

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void Init() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void Update() override;

		//-----------------------------------------------------------
		//! @brief 現在のズーム倍率取得
		//! @return 現在のズーム倍率
		//-----------------------------------------------------------
		float GetZoom() const;

		//-----------------------------------------------------------
		//! @brief ズーム倍率設定
		//! @param [in] zoom 設定するズーム倍率
		//-----------------------------------------------------------
		void SetZoom(float zoom);

	private:
		float zoom_ = 0.0f;       //!< 現在のズーム倍率
		float zoom_step_ = 0.0f;  //!< 1回の操作での増減量
		float zoom_min_ = 0.0f;   //!< 最小倍率
		float zoom_max_ = 0.0f;   //!< 最大倍率
	};
}
