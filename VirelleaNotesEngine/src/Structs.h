//----------------------------------------------------------------------------
//! @file   Structs.h
//! @brief  共通構造体の定義
//! @detail 2D位置、サイズ、画像情報、ボックス、カラーなどの汎用構造体を定義します。
//----------------------------------------------------------------------------
#pragma once

//--------------------------------------------------------
//! @struct FloatPos
//! 2D位置（float）
//--------------------------------------------------------
struct FloatPos
{
	float x = 0.0f;    //!< X位置
	float y = 0.0f;    //!< Y位置
};

//--------------------------------------------------------
//! @struct IntPos
//! 2D位置（int）
//--------------------------------------------------------
struct IntPos
{
	int x = 0;    //!< X位置
	int y = 0;    //!< Y位置
};

//--------------------------------------------------------
//! @struct FloatSize
//! サイズ（float）
//--------------------------------------------------------
struct FloatSize
{
	float w = 0.0f;    //!< 幅
	float h = 0.0f;    //!< 高さ
};

//--------------------------------------------------------
//! @struct IntSize
//! サイズ（int）
//--------------------------------------------------------
struct IntSize
{
	int w = 0;    //!< 幅
	int h = 0;    //!< 高さ
};

//--------------------------------------------------------
//! @struct ImageInputF
//! 画像入力情報（float）
//--------------------------------------------------------
struct ImageInputF
{
	int image = 0;      //!< 画像ハンドル
	float w = 0.0f;     //!< 幅
	float h = 0.0f;     //!< 高さ
	float rot = 0.0f;   //!< 回転角（ラジアン）
};

//--------------------------------------------------------
//! @struct ImageInputI
//! 画像入力情報（int）
//--------------------------------------------------------
struct ImageInputI
{
	int image = 0;      //!< 画像ハンドル
	int w = 0;          //!< 幅
	int h = 0;          //!< 高さ
	float rot = 0.0f;   //!< 回転角（ラジアン）
};

//--------------------------------------------------------
//! @struct ImagePropertyF
//! 画像プロパティ（float）
//--------------------------------------------------------
struct ImagePropertyF
{
	FloatPos pos;       //!< 位置
	int image = 0;      //!< 画像ハンドル
	int w = 0;          //!< 幅
	int h = 0;          //!< 高さ
	float rot = 0.0f;   //!< 回転角（ラジアン）
};

//--------------------------------------------------------
//! @struct BoxF
//! ボックス（float）
//--------------------------------------------------------
struct BoxF
{
	float x = 0.0f;    //!< 左上X
	float y = 0.0f;    //!< 左上Y
	float w = 0.0f;    //!< 幅
	float h = 0.0f;    //!< 高さ
};

//--------------------------------------------------------
//! @struct BoxI
//! ボックス（int）
//--------------------------------------------------------
struct BoxI
{
	int x = 0;    //!< 左上X
	int y = 0;    //!< 左上Y
	int w = 0;    //!< 幅
	int h = 0;    //!< 高さ
};

//--------------------------------------------------------
//! @struct RGB
//! カラー
//--------------------------------------------------------
struct RGB
{
	int r = 0;    //!< 赤
	int g = 0;    //!< 緑
	int b = 0;    //!< 青
};
