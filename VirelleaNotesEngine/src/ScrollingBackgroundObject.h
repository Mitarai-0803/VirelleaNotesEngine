//----------------------------------------------------------------------------
//! @file   ScrollingBackgroundObject.h
//! @brief  スクロール背景オブジェクト
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"

namespace UI
{
	//============================================================================
	//! @class  ScrollingBackgroundObject
	//! 無限スクロールする背景を表示するためのクラスです。
	//============================================================================
	class ScrollingBackgroundObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! 更新処理
		//-----------------------------------------------------------
		void OnUpdate() override;

		//-----------------------------------------------------------
		//! 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//!	終了処理
		//-----------------------------------------------------------
		void OnEnd() override;

		//-----------------------------------------------------------
		//! スクロール速度を設定
		//! @param [in] speed スクロール速度(ピクセル/フレーム)
		//-----------------------------------------------------------
		void SetScrollSpeed(float speed);

		//-----------------------------------------------------------
		//! 背景画像のハンドルを取得
		//! @return 背景画像ハンドル
		//-------------------------------------------------------
		int GetBackgroundHandle() const;

	private:
		int background_handle_;      //!< 背景画像ハンドル
		float scroll_offset_;        //!< スクロールオフセット
		float scroll_speed_;         //!< スクロール速度
		int image_height_;           //!< 画像の高さ
	};

}
