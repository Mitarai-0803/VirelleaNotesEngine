//----------------------------------------------------------------------------
//! @file   LoadMusicComponent.h
//! @brief  音源読み込みコンポーネントの宣言
//! @detail ファイルドラッグドロップで音源を読み込み、再生ハンドルを管理します。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"
#include <string>
#include <vector>

namespace Audio
{
	//============================================================================
	//! @class  LoadMusicComponent
	//! 音源読み込みと管理を行うためのクラスです。
	//============================================================================
	class LoadMusicComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief デストラクタ
		//-----------------------------------------------------------
		~LoadMusicComponent();

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void Init() override;

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void Update() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void Draw() override;

		//-----------------------------------------------------------
		//! @brief 音源ハンドル取得
		//! @return 音源ハンドル
		//-----------------------------------------------------------
		int GetHandle() const;

		//-----------------------------------------------------------
		//! @brief ソフト音源ハンドル取得
		//! @return ソフト音源ハンドル
		//-----------------------------------------------------------
		int GetSoftHandle() const;

		//-----------------------------------------------------------
		//! @brief 最大再生時間取得(ms)
		//! @return 最大再生時間
		//-----------------------------------------------------------
		int GetMaxPlayTime() const;

		//-----------------------------------------------------------
		//! @brief 読み込んだ音源ファイルパス取得
		//! @return ファイルパス（未読み込み時は空文字）
		//-----------------------------------------------------------
		const std::string& GetLoadedFilePath() const { return file_path_; }

		//-----------------------------------------------------------
		//! @brief 指定ファイルから音源を読み込み
		//! @param [in] path 読み込む音源ファイルパス
		//! @return 読み込み成功ならtrue
		//-----------------------------------------------------------
		bool LoadFromFile(const std::string& path);

	private:
		//-----------------------------------------------------------
		//! @brief 画面中央に文字列描画
		//! @param [in] text 描画文字列
		//! @param [in] y Y座標
		//! @param [in] color 色
		//! @param [in] width 幅倍率
		//-----------------------------------------------------------
		void DrawCenterString(const std::string& text, int y, unsigned int color, int width);

		int sound_handle_ = 0;                 //!< 音源ハンドル
		int soft_handle_ = 0;                  //!< ソフト音源ハンドル
		int max_play_time_ = 0;                //!< 最大再生時間(ms)
		int reload_recast_count_ = 0;          //!< 再読み込み待機カウント
		int load_recast_frame_ = 0;            //!< 読み込みリキャストフレーム
		bool one_load_flag_ = false;           //!< 一度だけ読み込むフラグ
		std::string file_path_ {};             //!< 読み込んだ音源ファイルパス
		std::vector<char> file_path_buffer_ {}; //!< ファイルパス取得用バッファ
		int normal_text_width_ = 0;            //!< 通常テキストの幅
		int error_text_width1_ = 0;            //!< エラーテキスト1の幅
	};
}
