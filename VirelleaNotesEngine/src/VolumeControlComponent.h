//----------------------------------------------------------------------------
//! @file   VolumeControlComponent.h
//! @brief  音量調整コンポーネントの宣言
//! @detail 上下キーで音量を調整するコンポーネントを定義します。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"

namespace Audio
{
	//============================================================================
	//! @class  VolumeControlComponent
	//! 音量調整を行うためのクラスです。
	//============================================================================
	class VolumeControlComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		VolumeControlComponent();

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void Update() override;

		//-----------------------------------------------------------
		//! @brief 現在音量取得
		//! @return 音量
		//-----------------------------------------------------------
		int GetVolume() const;

		//-----------------------------------------------------------
		//! @brief 音量設定
		//! @param [in] volume 設定する音量
		//-----------------------------------------------------------
		void SetVolume(int volume);

	private:
		int volume_ = 0;            //!< 現在の音量
		int hold_frame_count_ = 0;  //!< キー押下継続フレーム数
	};
}
