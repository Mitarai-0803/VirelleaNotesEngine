//----------------------------------------------------------------------------
//! @file   Engine.h
//! @brief  ゲームエンジンの宣言
//! @detail GameObjectのライフサイクルを一括管理するクラスを定義します。
///----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include <vector>
#include <memory>

namespace Engine
{
	//============================================================================
	//! @class  Engine
	//! GameObjectのライフサイクルを一括管理するためのクラスです。
	//============================================================================
	class Engine
	{
	public:
		//-----------------------------------------------------------
		//! @brief GameObject追加
		//! @param [in] obj 追加するGameObject
		//-----------------------------------------------------------
		void AddObject(std::shared_ptr<GameObject> obj);

		//-----------------------------------------------------------
		//! @brief 登録されている全てのGameObject更新
		//-----------------------------------------------------------
		void UpdateAll();

		//-----------------------------------------------------------
		//! @brief 登録されている全てのGameObject描画
		//-----------------------------------------------------------
		void DrawAll();

		//-----------------------------------------------------------
		//! @brief 登録されている全てのGameObjectの終了処理呼び出し
		//-----------------------------------------------------------
		void EndAll();

	private:
		std::vector<std::shared_ptr<GameObject>> gameObjects;    //!< 登録されているGameObjectの一覧
	};
}