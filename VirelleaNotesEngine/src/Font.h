//----------------------------------------------------------------------------
//! @file   Font.h
//! @brief  フォント管理の宣言
//! @detail 各サイズのフォントデータをロードし、管理する機能を定義します。
//----------------------------------------------------------------------------
#pragma once

namespace Font
{
	//--------------------------------------------------------
	//! @enum FontIndex
	//! フォントサイズごとのインデックス定義
	//--------------------------------------------------------
	enum FontIndex
	{
		FONT_SIZE_70_INDEX = 0,  //!< フォントサイズ70のインデックス
		FONT_SIZE_60_INDEX,      //!< フォントサイズ60のインデックス
		FONT_SIZE_50_INDEX,      //!< フォントサイズ50のインデックス
		FONT_SIZE_40_INDEX,      //!< フォントサイズ40のインデックス
		FONT_SIZE_30_INDEX,      //!< フォントサイズ30のインデックス
		FONT_SIZE_20_INDEX,      //!< フォントサイズ20のインデックス
		FONT_SIZE_10_INDEX,      //!< フォントサイズ10のインデックス
		FONT_MAX                 //!< フォントの最大数
	};

	//-----------------------------------------------------------
	//! @brief フォント初期化
	//-----------------------------------------------------------
	void FontInit();

	//-----------------------------------------------------------
	//! @brief フォント解放
	//-----------------------------------------------------------
	void FontExit();

	//-----------------------------------------------------------
	//! @brief フォントハンドル取得
	//! @param [in] font_index フォントサイズインデックス
	//! @return 指定インデックスのフォントハンドル
	//-----------------------------------------------------------
	int GetFont(int font_index);

	static int font_handle[FONT_MAX] = { 0 };    //!< フォントハンドル
}