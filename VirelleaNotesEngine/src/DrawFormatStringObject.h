//----------------------------------------------------------------------------
//! @file   DrawFormatStringObject.h
//! @brief  フォーマット文字列描画オブジェクトの宣言
//! @detail 名前付きプレースホルダーによるフォーマット文字列描画を提供します。
//----------------------------------------------------------------------------
#pragma once
#include <string>
#include <unordered_map>
#include <variant>
#include "GameObject.h"

namespace UI
{
	//============================================================================
	//! @class  DrawFormatStringObject
	//! フォーマット文字列を描画するためのクラスです。
	//============================================================================
	class DrawFormatStringObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void OnInit() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void OnDraw() override;

		//-----------------------------------------------------------
		//! @brief フォーマット文字列設定
		//! @param [in] fmt フォーマット文字列（例: "Score: {score}"）
		//-----------------------------------------------------------
		void SetFormat(const std::string& fmt);

		//-----------------------------------------------------------
		//! @brief フォーマット用パラメータ設定（整数）
		//! @param [in] name パラメータの名前
		//! @param [in] v 設定する整数値
		//-----------------------------------------------------------
		void SetParam(const std::string& name, int v);

		//-----------------------------------------------------------
		//! @brief フォーマット用パラメータ設定（浮動小数点）
		//! @param [in] name パラメータの名前
		//! @param [in] v 設定する浮動小数点値
		//-----------------------------------------------------------
		void SetParam(const std::string& name, float v);

		//-----------------------------------------------------------
		//! @brief フォーマット用パラメータ設定（文字列）
		//! @param [in] name パラメータの名前
		//! @param [in] v 設定する文字列
		//-----------------------------------------------------------
		void SetParam(const std::string& name, const std::string& v);

		//-----------------------------------------------------------
		//! @brief パラメータをフォーマット文字列に展開
		//-----------------------------------------------------------
		void ApplyFormat();

		//-----------------------------------------------------------
		//! @brief 座標設定
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//-----------------------------------------------------------
		void SetPos(float x, float y);

		//-----------------------------------------------------------
		//! @brief 色設定
		//! @param [in] color 色
		//-----------------------------------------------------------
		void SetColor(unsigned int color);

		//-----------------------------------------------------------
		//! @brief フォントハンドル設定
		//! @param [in] h フォントハンドル
		//-----------------------------------------------------------
		void SetFontHandle(int h);

	private:
		std::string format_;                                                           //!< 元のフォーマット文字列
		std::string formatted_;                                                        //!< プレースホルダー展開後の文字列
		std::unordered_map<std::string, std::variant<int, float, std::string>> params_; //!< パラメータ一覧
		struct { float x, y; } pos_;                                                   //!< 描画座標
		unsigned int color_;                                                           //!< 色
		int font_handle_;                                                              //!< フォントハンドル（0 = デフォルト）

		bool format_dirty_ = true;                                                      //!< フォーマット再計算フラグ
	};
}