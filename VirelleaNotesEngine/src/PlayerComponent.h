#pragma once
#include "ComponentBase.h"

//============================================================================
//! @class  PlayerComponent
//! プレイヤー操作・ノーツ判定・スコア管理を行うためのクラスです。
//============================================================================
class PlayerComponent : public ComponentBase
{
public:
	//-----------------------------------------------------------
	//! @brief コンストラクタ
	//-----------------------------------------------------------
	PlayerComponent() = default;

	//-----------------------------------------------------------
	//! @brief デストラクタ
	//-----------------------------------------------------------
	~PlayerComponent() override = default;

	//-----------------------------------------------------------
	//! @brief 初期化処理
	//-----------------------------------------------------------
	void Init() override;

	//-----------------------------------------------------------
	//! @brief 更新処理
	//-----------------------------------------------------------
	void Update() override;

	//-----------------------------------------------------------
	//! @brief 描画処理
	//-----------------------------------------------------------
	void Draw() override;

	//-----------------------------------------------------------
	//! @brief 終了処理
	//-----------------------------------------------------------
	void End() override;

private:
	int x = 0;              //!< プレイヤーX位置
	int y = 0;              //!< プレイヤーY位置
	int hitBoxWidth = 0;    //!< 当たり判定幅
	int hitBoxHeight = 0;   //!< 当たり判定高さ
	int score = 0;          //!< スコア
	int combo = 0;          //!< コンボ
	int handle = 0;         //!< DX画像ハンドル
};
