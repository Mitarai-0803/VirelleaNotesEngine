//----------------------------------------------------------------------------
//! @file   DrawBoxComponent.h
//! @brief  四角形描画コンポーネントの宣言
//! @detail 四角形を描画するコンポーネントを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "ComponentBase.h"
#include "Structs.h"

namespace UI
{
	//============================================================================
	//! @class  DrawBoxComponent
	//! 四角形を描画するためのクラスです。
	//============================================================================
	class DrawBoxComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		DrawBoxComponent();

		//-----------------------------------------------------------
		//! @brief 初期化処理
		//-----------------------------------------------------------
		void Init() override;

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void Draw() override;

		//-----------------------------------------------------------
		//! @brief サイズ設定
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//! @param [in] w 幅
		//! @param [in] h 高さ
		//-----------------------------------------------------------
		void SetBoxSize(float x, float y, float w, float h);

		//-----------------------------------------------------------
		//! @brief 色設定
		//! @param [in] r 赤
		//! @param [in] g 緑
		//! @param [in] b 青
		//-----------------------------------------------------------
		void SetColor(int r, int g, int b);

	private:
		BoxF drawBox_ = { 0 };       //!< 描画矩形
		RGB color_ = { 0, 0, 0 };    //!< 色

		// 描画用キャッシュ
		int draw_x_int_ = 0;         //!< 描画X座標(整数)
		int draw_y_int_ = 0;         //!< 描画Y座標(整数)
		int draw_w_int_ = 0;         //!< 描画幅(整数)
		int draw_h_int_ = 0;         //!< 描画高さ(整数)
		int color_handle_ = 0;       //!< キャッシュされたGetColorの戻り値
	};
}
