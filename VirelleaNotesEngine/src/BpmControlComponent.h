//----------------------------------------------------------------------------
//! @file   BpmControlComponent.h
//! @brief  BPM制御コンポーネントの宣言
//! @detail BPMの調整、グリッド描画などの機能を提供します。
//----------------------------------------------------------------------------
#pragma once

#include "ComponentBase.h"
#include <algorithm>

namespace UI
{
	//============================================================================
	//! @class  BpmControlComponent
	//! BPM制御を行うためのコンポーネントです。
	//============================================================================
	class BpmControlComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		BpmControlComponent();

		//-----------------------------------------------------------
		//! @brief 更新処理
		//-----------------------------------------------------------
		void Update() override;

		//-----------------------------------------------------------
		//! @brief 現在BPM取得
		//! @return 現在のBPM
		//-----------------------------------------------------------
		int GetBpm() const;

		//-----------------------------------------------------------
		//! @brief BPM設定
		//! @param [in] bpm 設定するBPM
		//-----------------------------------------------------------
		void SetBpm(int bpm);

	private:
		//-----------------------------------------------------------
		//! @brief BPMグリッド描画
		//-----------------------------------------------------------
		void DrawBpmGrid();

		int bpm_ = 0;                 //!< 現在BPM
		int hold_frame_count_ = 0;    //!< 押下フレーム数
		int line_count_ = 0;          //!< ライン数
		int max_play_time_ms_ = 0;    //!< 最大再生時間(ms)
		float zoom_ = 0.0f;           //!< ズーム倍率
		int scroll_y_ = 0;            //!< スクロール量Y
	};
}
