//----------------------------------------------------------------------------
//! @file   ComponentBase.h
//! @brief  コンポーネント基底クラスの宣言
//! @detail 全てのコンポーネントが継承する基底クラスを定義します。
//----------------------------------------------------------------------------
#pragma once

//============================================================================
//! @class  ComponentBase
//! 全てのコンポーネントが継承する基底クラスです。
//============================================================================
class ComponentBase
{
public:
	//-----------------------------------------------------------
	//! @brief コンストラクタ
	//-----------------------------------------------------------
	ComponentBase() = default;

	//-----------------------------------------------------------
	//! @brief デストラクタ
	//-----------------------------------------------------------
	virtual ~ComponentBase() = default;

	//-----------------------------------------------------------
	//! @brief 初期化処理
	//-----------------------------------------------------------
	virtual void Init() {}

	//-----------------------------------------------------------
	//! @brief フレーム更新
	//-----------------------------------------------------------
	virtual void Update() {}

	//-----------------------------------------------------------
	//! @brief 描画処理
	//-----------------------------------------------------------
	virtual void Draw() {}

	//-----------------------------------------------------------
	//! @brief 終了処理
	//-----------------------------------------------------------
	virtual void End() {}

private:
	// プライベートメンバや関数があればここに追加
};
