//----------------------------------------------------------------------------
//! @file   NoteTypeButton.cpp
//! @brief  ノーツタイプボタンの実装
//! @detail ノーツタイプを切り替えるUIボタンの機能を提供します。
//----------------------------------------------------------------------------
#include "NoteTypeButton.h"

namespace UI
{
	//-----------------------------------------------------------
	//! @brief 初期化処理
	//-----------------------------------------------------------
	void NoteTypeButton::OnInit()
	{
		Init();
		SetInputType(UI::ButtonInputType::ONE_SHOT);
		SetOff();
	}

	//-----------------------------------------------------------
	//! @brief 更新処理
	//-----------------------------------------------------------
	void NoteTypeButton::OnUpdate()
	{
		Update();
	}

	//-----------------------------------------------------------
	//! @brief 描画処理
	//-----------------------------------------------------------
	void NoteTypeButton::OnDraw()
	{
		Draw();
	}

	//-----------------------------------------------------------
	//! @brief 終了処理
	//-----------------------------------------------------------
	void NoteTypeButton::OnEnd()
	{
		End();
	}

	//-----------------------------------------------------------
	//! @brief ノーツタイプ取得
	//-----------------------------------------------------------
	int NoteTypeButton::GetNoteType() const
	{
		return note_type_;
	}

	//-----------------------------------------------------------
	//! @brief ノーツタイプ設定
	//-----------------------------------------------------------
	void NoteTypeButton::SetNoteType(int note_type)
	{
		note_type_ = note_type;
	}

	//-----------------------------------------------------------
	//! @brief ボタンの位置設定
	//-----------------------------------------------------------
	void NoteTypeButton::SetPos(float x, float y)
	{
		pos_.x = x;
		pos_.y = y;
	}
}