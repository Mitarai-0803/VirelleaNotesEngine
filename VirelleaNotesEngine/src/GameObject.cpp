//----------------------------------------------------------------------------
//! @file   GameObject.cpp
//! @brief  ゲームオブジェクトの実装
//! @detail コンポーネントを管理し、ライフサイクルを管理する機能を提供します。
//----------------------------------------------------------------------------
#include "GameObject.h"


//-----------------------------------------------------------
//! @brief デストラクタ
//-----------------------------------------------------------
GameObject::~GameObject()
{
	End();
}

//-----------------------------------------------------------
//! @brief 初期化処理
//-----------------------------------------------------------
void GameObject::Init()
{
	// コンポーネントの初期化呼び出し
	for (auto& comp : components_)
	{
		comp->Init();
	}

	OnInit();
}

//-----------------------------------------------------------
//! @brief 更新処理
//-----------------------------------------------------------
void GameObject::Update()
{
	for (auto& comp : components_)
	{
		comp->Update();
	}

	OnUpdate();
}

//-----------------------------------------------------------
//! @brief 描画処理
//-----------------------------------------------------------
void GameObject::Draw()
{
	for (auto& comp : components_)
	{
		comp->Draw();
	}

	OnDraw();
}

//-----------------------------------------------------------
//! @brief 終了処理
//-----------------------------------------------------------
void GameObject::End()
{
	for (auto& comp : components_)
	{
		comp->End();
	}

	components_.clear();

	OnEnd();
}