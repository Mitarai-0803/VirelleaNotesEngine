//----------------------------------------------------------------------------
//! @file   NoteObject.h
//! @brief  ノーツオブジェクトの宣言
//! @detail 譜面エディタで配置されるノーツの管理を行います。
//----------------------------------------------------------------------------
#pragma once
#include "GameObject.h"
#include "ImageObject.h"

namespace UI
{
	//--------------------------------------------------------
	//! @enum NOTE_TYPE
	//! ノーツタイプの定義
	//--------------------------------------------------------
	enum NOTE_TYPE
	{
		NOTE_TYPE_MIN = -1,    //!< 最小値
		NOTE_TYPE_TAP,         //!< タップノーツ
		NOTE_TYPE_HOLD_START,  //!< ホールドノーツ開始
		NOTE_TYPE_HOLD_END,    //!< ホールドノーツ終了
		NOTE_TYPE_SYNC,        //!< 同時押しノーツ
		NOTE_TYPE_DELETE,      //!< ノーツ削除
		NOTE_TYPE_MAX          //!< 最大値
	};

	//============================================================================
	//! @class  NoteObject
	//! 譜面エディタで配置されるノーツを管理するためのクラスです。
	//============================================================================
	class NoteObject : public GameObject
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//! @param [in] note_type ノーツタイプ
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//! @param [in] time_ms 生成時間（ミリ秒）
		//-----------------------------------------------------------
		NoteObject(int note_type, float x, float y, int time_ms);

		//-----------------------------------------------------------
		//! @brief デフォルトコンストラクタ
		//-----------------------------------------------------------
		NoteObject() = default;

		//-----------------------------------------------------------
		//! @brief ノーツの位置設定
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//-----------------------------------------------------------
		void SetPosition(float x, float y);

		//-----------------------------------------------------------
		//! @brief 描画処理
		//! @param [in] scroll スクロール量
		//! @param [in] zoom ズーム率
		//-----------------------------------------------------------
		void OnDraw(float scroll, float zoom) override;

		//-----------------------------------------------------------
		//! @brief ノーツのX座標取得
		//! @return X座標
		//-----------------------------------------------------------
		float GetPosX() const;

		//-----------------------------------------------------------
		//! @brief ノーツのY座標取得
		//! @return Y座標
		//-----------------------------------------------------------
		float GetPosY() const;

		//-----------------------------------------------------------
		//! @brief ノーツのタイプ取得
		//! @return ノーツタイプ
		//-----------------------------------------------------------
		int GetType() const;

		//-----------------------------------------------------------
		//! @brief ノーツの生成秒数取得
		//! @return 生成秒数（フレーム数）
		//-----------------------------------------------------------
		int GetFrameTime() const;

		//-----------------------------------------------------------
		//! @brief ノーツのライン番号取得
		//! @return ライン番号
		//-----------------------------------------------------------
		int GetLineIndex() const;

		//-----------------------------------------------------------
		//! @brief 初期化メソッド
		//! @param [in] note_type ノートの種類
		//! @param [in] x X座標
		//! @param [in] y Y座標
		//! @param [in] time_frame 時間（フレーム数）
		//-----------------------------------------------------------
		void Initialize(int note_type, float x, float y, int time_frame);

		//-----------------------------------------------------------
		//! @brief ノーツの種類設定
		//! @param [in] note_type 設定するノーツの種類
		//-----------------------------------------------------------
		void SetType(int note_type) { note_type_ = note_type; }

		//-----------------------------------------------------------
		//! @brief ノーツの生成時間を秒で設定
		//! @param [in] seconds 生成時間（秒）
		//-----------------------------------------------------------
		void SetTimeFromSeconds(float seconds);

		//-----------------------------------------------------------
		//! @brief ノーツの生成時間設定
		//! @param [in] timeMs 生成時間（ミリ秒）
		//-----------------------------------------------------------
		void SetTimeMs(int timeMs);

	private:
		float pos_x_ = 0.0f;                              //!< X座標
		float pos_y_ = 0.0f;                              //!< Y座標
		int line_index_ = 0;                              //!< ライン番号
		int note_type_ = 0;                               //!< ノーツタイプ
		int time_frame_ = 0;                              //!< ノーツの生成秒数
		ImageObject notes_images_[NOTE_TYPE_MAX] = {};    //!< ノーツ画像

		// 描画用キャッシュ
		float draw_x_ = 0.0f;           //!< 描画X座標キャッシュ
		float draw_y_ = 0.0f;           //!< 描画Y座標キャッシュ
		float draw_zoom_ratio_ = 1.0f;  //!< 描画時のズーム比率キャッシュ
	};

	//-----------------------------------------------------------
	//! @brief NoteObject生成
	//! @param [in] note_type ノーツタイプ
	//! @param [in] x X座標
	//! @param [in] y Y座標
	//! @param [in] time_ms 時間（ミリ秒）
	//! @return 生成されたNoteObject
	//-----------------------------------------------------------
	std::shared_ptr<NoteObject> CreateNoteObject(int note_type, float x, float y, int time_ms);

	//-----------------------------------------------------------
	//! @brief NoteObject破棄
	//! @param [in] note 破棄するNoteObject
	//-----------------------------------------------------------
	void DestroyNoteObject(std::shared_ptr<NoteObject> note);
}
