//----------------------------------------------------------------------------
//! @file   Engine.cpp
//! @brief  ゲームエンジンの実装
//! @detail GameObjectのライフサイクルを一括管理する機能を提供します。
//----------------------------------------------------------------------------
#include "Engine.h"

namespace Engine
{
	//-----------------------------------------------------------
	//! @brief GameObject追加
	//-----------------------------------------------------------
	void Engine::AddObject(std::shared_ptr<GameObject> obj)
	{
		gameObjects.push_back(obj);
	}

	//-----------------------------------------------------------
	//! @brief 登録されている全てのGameObject更新
	//-----------------------------------------------------------
	void Engine::UpdateAll()
	{
		for (auto& obj : gameObjects)
		{
			obj->Update();
		}
	}

	//-----------------------------------------------------------
	//! @brief 登録されている全てのGameObject描画
	//-----------------------------------------------------------
	void Engine::DrawAll()
	{
		for (auto& obj : gameObjects)
		{
			obj->Draw();
		}
	}

	//-----------------------------------------------------------
	//! @brief 登録されている全てのGameObjectの終了処理呼び出し
	//-----------------------------------------------------------
	void Engine::EndAll()
	{
		for (auto& obj : gameObjects)
		{
			obj->End();
		}
	}
}