//----------------------------------------------------------------------------
//! @file   GridComponent.h
//! @brief  グリッドコンポーネントの宣言
//! @detail 秒グリッド、BPMグリッド、縦ラインを描画するコンポーネントを定義します。
//----------------------------------------------------------------------------
#pragma once
#include "ComponentBase.h"
#include "UIConstants.h"
#include "Colors.h"

namespace UI
{
	//============================================================================
	//! @class  GridComponent
	//! 秒グリッド、BPMグリッド、縦ラインを描画するためのクラスです。
	//============================================================================
	class GridComponent : public ComponentBase
	{
	public:
		//-----------------------------------------------------------
		//! @brief コンストラクタ
		//-----------------------------------------------------------
		GridComponent();

		//-----------------------------------------------------------
		//! @brief 描画処理
		//-----------------------------------------------------------
		void Draw();

		//-----------------------------------------------------------
		//! @brief 描画ライン数設定
		//! @param [in] line_count 描画する縦ライン数
		//-----------------------------------------------------------
		void SetLineCount(int line_count);

		//-----------------------------------------------------------
		//! @brief 最大再生時間設定
		//! @param [in] max_play_time_ms 最大再生時間(ms)
		//-----------------------------------------------------------
		void SetMaxPlayTime(int max_play_time_ms);

		//-----------------------------------------------------------
		//! @brief BPM設定
		//! @param [in] bpm BPM値
		//-----------------------------------------------------------
		void SetBpm(int bpm);

		//-----------------------------------------------------------
		//! @brief 表示倍率（ズーム）設定
		//! @param [in] zoom 表示倍率
		//-----------------------------------------------------------
		void SetZoom(float zoom);

		//-----------------------------------------------------------
		//! @brief スクロール量設定
		//! @param [in] scroll_y スクロール量
		//-----------------------------------------------------------
		void SetScrollY(int scroll_y);

		//-----------------------------------------------------------
		//! @brief 最大スクロールY座標取得
		//! @return 最大スクロールY座標
		//-----------------------------------------------------------
		int GetMaxScrollY();

		//-----------------------------------------------------------
		//! @brief BPM取得
		//! @return BPM値
		//-----------------------------------------------------------
		int GetBpm();

	private:
		int line_count_ = 0;          //!< 描画する縦ライン数
		int max_play_time_ms_ = 0;    //!< 最大再生時間(ms)
		int bpm_ = 0;                 //!< BPM値
		float zoom_ = 0.0f;           //!< 表示倍率
		int scroll_y_ = 0;            //!< スクロール量
		int max_scroll_y_ = 0;        //!< 最大スクロールY座標
	};
}
